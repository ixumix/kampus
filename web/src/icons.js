// «В работе» живёт: половинка медленно обходит круг (фон «Живого интерфейса»). Статус сменился на глазах —
// новая заливка проступает из центра (например, «В работе» → «Готова», когда справка готова по сценарию).
export function StatusGlyph({ status, size = 14 }) {
  const prev = useRef(status);
  const changed = useRef(false);
  if (prev.current !== status) { changed.current = true; prev.current = status; }
  const c = 7, r = 5.75;
  const ring = html`<circle cx=${c} cy=${c} r=${r} fill="none" stroke="currentColor" stroke-width="1.3" />`;
  let inner = null;
  if (status === "accepted") inner = html`<circle cx=${c} cy=${c} r=${r} fill="none" stroke="currentColor" stroke-width="1.3" stroke-dasharray="2.2 2.2" />`;
  else if (status === "in_progress") inner = html`${ring}<path class="sg-half" d="M7 3.5A3.5 3.5 0 0 1 7 10.5Z" fill="currentColor" />`;
  else if (status === "ready" || status === "answered") inner = html`${ring}<circle cx=${c} cy=${c} r="3.5" fill="currentColor" />`;
  else if (status === "received") inner = html`<circle cx=${c} cy=${c} r="6.5" fill="currentColor" /><path d="M4.4 7.2 6.2 9l3.4-3.8" fill="none" stroke="var(--panel)" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" />`;
  else if (status === "cancelled" || status === "rejected") inner = html`${ring}<path d="M4.6 9.4l4.8-4.8" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" />`;
  else inner = ring;
  return html`<svg class=${"status" + (changed.current ? " sg-changed" : "")} key=${changed.current ? status : "s"} width=${size} height=${size} viewBox="0 0 14 14" aria-hidden="true">${inner}</svg>`;
}

